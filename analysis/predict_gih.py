def main() -> None:
    rows = []
    missing = []
    extra = set(TARGETS) - {c["name"] for c in FRA}
    for card in FRA:
        name = card["name"]
        if name not in TARGETS:
            missing.append(name)
            continue
        model_wr = BASELINE + float(card["blend_excess"])
        final = TARGETS[name]
        rows.append(
            {
                "collector_number": int(card["cn"]),
                "name": name,
                "rarity": card["rarity"],
                "colors": card.get("colors") or "",
                "mana_cost": card.get("mana_cost") or "",
                "type_line": card.get("type_line") or "",
                "model_gih_win_rate": round(model_wr, 4),
                "gih_win_rate": round(final, 4),
                "expert_delta": round(final - model_wr, 4),
            }
        )
    if missing or extra:
        raise SystemExit(f"missing={missing[:12]} n={len(missing)} extra={sorted(extra)[:12]} n={len(extra)}")
    df = pd.DataFrame(rows).sort_values("collector_number")
    out_dir = ROOT / "predictions"
    out_dir.mkdir(parents=True, exist_ok=True)
    public = df[["name", "collector_number", "rarity", "gih_win_rate"]]
    public.to_csv(out_dir / "reality_fracture_gih.csv", index=False)
    df.to_csv(ROOT / "analysis" / "card_scores.csv", index=False)
    print("cards", len(df))
    print("mean", round(df.gih_win_rate.mean(), 4), "std", round(df.gih_win_rate.std(), 4))
    print(df.groupby("rarity").gih_win_rate.agg(["count", "mean", "median", "min", "max"]).round(4))
    print("p05", round(df.gih_win_rate.quantile(0.05), 4), "p95", round(df.gih_win_rate.quantile(0.95), 4))
    print("above 0.62", int((df.gih_win_rate >= 0.62).sum()), "below 0.52", int((df.gih_win_rate < 0.52).sum()))
    print("mean |delta|", round(df.expert_delta.abs().mean(), 4))


if __name__ == "__main__":
    main()
